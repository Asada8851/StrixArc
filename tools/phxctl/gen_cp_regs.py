#!/usr/bin/env python3
"""Generates cp_regs_gc11_5.h: every CP_* register of GC 11.5 that is safe to read (no data ports, FIFOs, index/mutex,
dequeue/reset requests or read-to-clear status), as absolute MMIO dwords, for `mesboot cpscan`.

usage: gen_cp_regs.py <linux>/drivers/gpu/drm/amd/include/asic_reg/gc/gc_11_5_0_offset.h > cp_regs_gc11_5.h
"""
import re
import sys

BASE = {0: 0x1260, 1: 0xA000}   # GC segments 0 and 1 (the 880M's ip_discovery)
SKIP = re.compile(r'DATA|UCODE|FIFO|_INDEX|MUTEX|DEQUEUE|SOFT_RESET|_REQ$|DOORBELL_CLEAR|INT_STATUS|_ACK')

text = open(sys.argv[1]).read()
regs = []
for m in re.finditer(r'#define reg(CP_\w+?)\s+(0x[0-9a-fA-F]+)\n#define reg\1_BASE_IDX\s+(\d)', text):
    name, off, idx = m.group(1), int(m.group(2), 16), int(m.group(3))
    if idx in BASE and not SKIP.search(name):
        regs.append((BASE[idx] + off, name))
regs.sort()
print("/* Generated by gen_cp_regs.py from gc_11_5_0_offset.h: readable CP registers of GC 11.5 (absolute dwords). */")
print("static const struct { uint32_t reg; const char *name; } kCpRegsGc115[] = {")
for reg, name in regs:
    print(f'   {{0x{reg:05x}, "{name}"}},')
print("};")
