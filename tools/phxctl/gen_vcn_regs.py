#!/usr/bin/env python3
"""Generates vcn_regs_strix.h: the VCN 4.0.5 and MMHUB 3.3 registers `mesboot vcn` uses, as absolute MMIO dwords of the
880M (its ip_discovery bases), the field masks/shifts the DPG start writes, and the DPG SRAM offset of each VCN
register (SOC15_DPG_MODE_OFFSET in Linux amdgpu_vcn.h: the address VCN's indirect register loader takes).

usage: gen_vcn_regs.py <linux>/drivers/gpu/drm/amd/include/asic_reg > src/amd/vcn_regs_strix.h
"""
import re
import sys

R = sys.argv[1]
VCN_BASE = [0x7800, 0x7E00, 0x3C030000]          # VCN instance 0 (the 880M has one)
MMHUB_BASE = [0x13200, 0x1A000, 0x2408800, 0x3C088000]

VCN_REGS = """UVD_POWER_STATUS UVD_STATUS UVD_RB_BASE_LO UVD_RB_BASE_HI UVD_RB_SIZE UVD_RB_RPTR UVD_RB_WPTR VCN_RB_ENABLE
VCN_RB1_DB_CTRL UVD_VCPU_CNTL UVD_MASTINT_EN UVD_LMI_CTRL UVD_LMI_CTRL2 UVD_MPC_CNTL UVD_MPC_SET_MUXA0 UVD_MPC_SET_MUXB0
UVD_MPC_SET_MUX UVD_LMI_VCPU_CACHE_64BIT_BAR_LOW UVD_LMI_VCPU_CACHE_64BIT_BAR_HIGH UVD_VCPU_CACHE_OFFSET0
UVD_VCPU_CACHE_SIZE0 UVD_LMI_VCPU_CACHE1_64BIT_BAR_LOW UVD_LMI_VCPU_CACHE1_64BIT_BAR_HIGH UVD_VCPU_CACHE_OFFSET1
UVD_VCPU_CACHE_SIZE1 UVD_LMI_VCPU_CACHE2_64BIT_BAR_LOW UVD_LMI_VCPU_CACHE2_64BIT_BAR_HIGH UVD_VCPU_CACHE_OFFSET2
UVD_VCPU_CACHE_SIZE2 UVD_LMI_VCPU_NC0_64BIT_BAR_LOW UVD_LMI_VCPU_NC0_64BIT_BAR_HIGH UVD_VCPU_NONCACHE_OFFSET0
UVD_VCPU_NONCACHE_SIZE0 UVD_GFX10_ADDR_CONFIG""".split()
MMHUB_REGS = """MMMC_VM_FB_LOCATION_BASE MMMC_VM_FB_LOCATION_TOP MMMC_VM_FB_OFFSET MMMC_VM_AGP_BASE MMMC_VM_AGP_BOT
MMMC_VM_AGP_TOP MMMC_VM_SYSTEM_APERTURE_LOW_ADDR MMMC_VM_SYSTEM_APERTURE_HIGH_ADDR
MMMC_VM_SYSTEM_APERTURE_DEFAULT_ADDR_LSB MMMC_VM_SYSTEM_APERTURE_DEFAULT_ADDR_MSB MMMC_VM_MX_L1_TLB_CNTL MMVM_L2_CNTL
MMVM_L2_CNTL2 MMVM_L2_CNTL3 MMVM_L2_CNTL4 MMVM_L2_CNTL5 MMVM_L2_PROTECTION_FAULT_CNTL MMVM_L2_PROTECTION_FAULT_CNTL2
MMVM_L2_PROTECTION_FAULT_STATUS MMVM_L2_PROTECTION_FAULT_ADDR_LO32 MMVM_L2_PROTECTION_FAULT_ADDR_HI32
MMVM_L2_PROTECTION_FAULT_DEFAULT_ADDR_LO32 MMVM_L2_PROTECTION_FAULT_DEFAULT_ADDR_HI32
MMVM_L2_CONTEXT1_IDENTITY_APERTURE_LOW_ADDR_LO32 MMVM_L2_CONTEXT1_IDENTITY_APERTURE_LOW_ADDR_HI32
MMVM_L2_CONTEXT1_IDENTITY_APERTURE_HIGH_ADDR_LO32 MMVM_L2_CONTEXT1_IDENTITY_APERTURE_HIGH_ADDR_HI32
MMVM_L2_CONTEXT_IDENTITY_PHYSICAL_OFFSET_LO32 MMVM_L2_CONTEXT_IDENTITY_PHYSICAL_OFFSET_HI32 MMVM_CONTEXT0_CNTL
MMVM_CONTEXT1_CNTL MMVM_CONTEXT0_PAGE_TABLE_BASE_ADDR_LO32 MMVM_CONTEXT0_PAGE_TABLE_BASE_ADDR_HI32
MMVM_CONTEXT0_PAGE_TABLE_START_ADDR_LO32 MMVM_CONTEXT0_PAGE_TABLE_START_ADDR_HI32
MMVM_CONTEXT0_PAGE_TABLE_END_ADDR_LO32 MMVM_CONTEXT0_PAGE_TABLE_END_ADDR_HI32 MMVM_CONTEXT1_PAGE_TABLE_START_ADDR_LO32
MMVM_CONTEXT1_PAGE_TABLE_START_ADDR_HI32 MMVM_CONTEXT1_PAGE_TABLE_END_ADDR_LO32 MMVM_CONTEXT1_PAGE_TABLE_END_ADDR_HI32
MMVM_INVALIDATE_ENG0_ADDR_RANGE_LO32 MMVM_INVALIDATE_ENG0_ADDR_RANGE_HI32 MMVM_INVALIDATE_ENG17_SEM
MMVM_INVALIDATE_ENG17_REQ MMVM_INVALIDATE_ENG17_ACK""".split()
FIELDS = """UVD_POWER_STATUS__UVD_POWER_STATUS UVD_POWER_STATUS__UVD_PG_MODE UVD_POWER_STATUS__UVD_PG_EN
UVD_VCPU_CNTL__PRB_TIMEOUT_VAL UVD_VCPU_CNTL__CLK_EN UVD_VCPU_CNTL__BLK_RST UVD_LMI_CTRL__WRITE_CLEAN_TIMER_EN
UVD_LMI_CTRL__REQ_MODE UVD_LMI_CTRL__CRC_RESET UVD_LMI_CTRL__MASK_MC_URGENT UVD_LMI_CTRL__DATA_COHERENCY_EN
UVD_LMI_CTRL__VCPU_DATA_COHERENCY_EN UVD_LMI_CTRL__WRITE_CLEAN_TIMER UVD_MPC_CNTL__REPLACEMENT_MODE
UVD_MPC_SET_MUXA0__VARA_1 UVD_MPC_SET_MUXA0__VARA_2 UVD_MPC_SET_MUXA0__VARA_3 UVD_MPC_SET_MUXA0__VARA_4
UVD_MPC_SET_MUXB0__VARB_1 UVD_MPC_SET_MUXB0__VARB_2 UVD_MPC_SET_MUXB0__VARB_3 UVD_MPC_SET_MUXB0__VARB_4
UVD_MPC_SET_MUX__SET_0 UVD_MPC_SET_MUX__SET_1 UVD_MPC_SET_MUX__SET_2 UVD_LMI_CTRL2__RE_OFLD_MIF_WR_REQ_NUM
UVD_MASTINT_EN__VCPU_EN VCN_RB_ENABLE__RB1_EN""".split()

# amdgpu_vcn.h / vcn_v4_0_5.c: the VCN register windows the DPG loader addresses by its own numbers
VCN_VID_SOC_ADDRESS_2_0, VCN_AON_SOC_ADDRESS_2_0 = 0x1FB00, 0x1F800
VCN_VID_IP_ADDRESS_2_0, VCN_AON_IP_ADDRESS_2_0 = 0x0, 0x30000


def offsets(path):
    t = open(path).read()
    off = dict((n, int(v, 16)) for n, v in re.findall(r'#define reg(\w+?)\s+(0x[0-9a-fA-F]+)\s*$', t, re.M))
    idx = dict((n, int(v)) for n, v in re.findall(r'#define reg(\w+)_BASE_IDX\s+(\d+)', t))
    return off, idx


def dpg_offset(absreg):
    a = (absreg << 2) & 0xFFFFF
    if VCN_VID_SOC_ADDRESS_2_0 <= a < VCN_VID_SOC_ADDRESS_2_0 + 0x2600:
        a = a - VCN_VID_SOC_ADDRESS_2_0 + VCN_VID_IP_ADDRESS_2_0
    elif VCN_AON_SOC_ADDRESS_2_0 <= a < VCN_AON_SOC_ADDRESS_2_0 + 0x600:
        a = a - VCN_AON_SOC_ADDRESS_2_0 + VCN_AON_IP_ADDRESS_2_0
    return a >> 2


print("/* Generated by gen_vcn_regs.py from Linux vcn_4_0_5 and mmhub_3_3_0 headers, with the 880M's ip_discovery bases")
print(" * (VCN 0x7800/0x7e00, MMHUB 0x13200/0x1a000): absolute MMIO dwords; VCN_DPG_* is the register's DPG SRAM")
print(" * address (Linux SOC15_DPG_MODE_OFFSET). */")
vo, vi = offsets(f"{R}/vcn/vcn_4_0_5_offset.h")
for n in VCN_REGS:
    a = VCN_BASE[vi[n]] + vo[n]
    print(f"#define VCN_{n:40} 0x{a:05x}u   /* DPG 0x{dpg_offset(a):05x} */")
    print(f"#define VCN_DPG_{n:36} 0x{dpg_offset(a):05x}u")
mo, mi = offsets(f"{R}/mmhub/mmhub_3_3_0_offset.h")
for n in MMHUB_REGS:
    print(f"#define {n:48} 0x{MMHUB_BASE[mi[n]] + mo[n]:05x}u")
sh = open(f"{R}/vcn/vcn_4_0_5_sh_mask.h").read()
for f in FIELDS:
    s = re.search(rf'#define {f}__SHIFT\s+(0x[0-9a-fA-F]+)', sh)
    m = re.search(rf'#define {f}_MASK\s+(0x[0-9a-fA-F]+L?)', sh)
    if not s or not m:
        sys.exit(f"no field {f}")
    print(f"#define {f + '__SHIFT':56} {s.group(1)}")
    print(f"#define {f + '_MASK':56} {m.group(1).rstrip('L')}u")
